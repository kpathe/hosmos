import {
  pgTable,
  uuid,
  integer,
  timestamp,
  text,
  index,
  unique,
  pgEnum,
} from "drizzle-orm/pg-core";
import { hostels } from "./hostels.js";
import { hostellers } from "./hostellers.js";

// ─────────────────────────────────────────────────────────────────────────────
// Bill Status Enum
// ─────────────────────────────────────────────────────────────────────────────

export const billStatusEnum = pgEnum("bill_status", ["unpaid", "paid"]);

// ─────────────────────────────────────────────────────────────────────────────
// Bill Item Type Enum
// ─────────────────────────────────────────────────────────────────────────────

export const billItemTypeEnum = pgEnum("bill_item_type", [
  "rent",
  "electricity",
  "security_deposit",
  "advance_allocation",
  "late_fine",
  "adjustment",
  "other",
]);

// ─────────────────────────────────────────────────────────────────────────────
// Bills
//
// One bill per hosteller per billing period (calendar month).
// Bills are generated by admin — no automated generation in MVP.
//
// PRD invariants:
//   - UNIQUE (hosteller_id, billing_period_year, billing_period_month)
//   - total_amount_paise is maintained (updated transactionally when items change)
//   - Paid bills are immutable — enforced in service layer
//   - Admission bills are generated AND paid at the same time during admission
// ─────────────────────────────────────────────────────────────────────────────

export const bills = pgTable(
  "bills",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    hostelId: uuid("hostel_id")
      .notNull()
      .references(() => hostels.id, { onDelete: "restrict" }),
    hostelerId: uuid("hosteller_id")
      .notNull()
      .references(() => hostellers.id, { onDelete: "restrict" }),

    /** Calendar year of the billing period (e.g., 2026) */
    billingPeriodYear: integer("billing_period_year").notNull(),
    /** Calendar month of the billing period (1-12) */
    billingPeriodMonth: integer("billing_period_month").notNull(),

    status: billStatusEnum("status").notNull().default("unpaid"),

    /**
     * Maintained sum of all bill_items.amount_paise for this bill.
     * Updated in the same transaction as any bill_item insert/update.
     * PRD decision OQ-6: stored for query performance.
     */
    totalAmountPaise: integer("total_amount_paise").notNull().default(0),

    generatedAt: timestamp("generated_at", { withTimezone: true }).notNull().defaultNow(),
    paidAt: timestamp("paid_at", { withTimezone: true }),

    /** UUID of the owner/manager who generated this bill */
    createdBy: uuid("created_by"),
    updatedBy: uuid("updated_by"),

    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    /** One bill per hosteller per billing period */
    unique("uq_bill_period").on(t.hostelerId, t.billingPeriodYear, t.billingPeriodMonth),
    index("idx_bills_hostel_id").on(t.hostelId),
    index("idx_bills_hosteller_id").on(t.hostelerId),
    index("idx_bills_period").on(t.hostelId, t.billingPeriodYear, t.billingPeriodMonth),
    index("idx_bills_status").on(t.status),
  ]
);

// ─────────────────────────────────────────────────────────────────────────────
// Bill Items
//
// Line items on a bill. Amount can be positive (charge) or negative (credit).
// The sum of all items for a bill must equal bills.total_amount_paise.
// ─────────────────────────────────────────────────────────────────────────────

export const billItems = pgTable(
  "bill_items",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    billId: uuid("bill_id")
      .notNull()
      .references(() => bills.id, { onDelete: "cascade" }),
    /** Denormalized for tenant-scoped queries */
    hostelId: uuid("hostel_id")
      .notNull()
      .references(() => hostels.id, { onDelete: "restrict" }),

    itemType: billItemTypeEnum("item_type").notNull(),

    /** Human-readable description, e.g., "Rent - October 2026" */
    description: text("description").notNull(),

    /**
     * Amount in paise.
     * Positive = charge to hosteller.
     * Negative = credit to hosteller (e.g., advance_allocation).
     */
    amountPaise: integer("amount_paise").notNull(),

    createdBy: uuid("created_by"),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    index("idx_bill_items_bill_id").on(t.billId),
    index("idx_bill_items_hostel_id").on(t.hostelId),
  ]
);

export type Bill = typeof bills.$inferSelect;
export type NewBill = typeof bills.$inferInsert;
export type BillItem = typeof billItems.$inferSelect;
export type NewBillItem = typeof billItems.$inferInsert;
